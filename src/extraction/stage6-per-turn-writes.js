    // last-write-wins by (field, circuit, board) — correct for VALUE state,
    // but it collapses two DISTINCT same-turn designation ops into one, so
    // the read-back layer (plan-pinned: "two designation changes on one
    // circuit → both speak") synthesises designation confirmations from
    // THIS log when it is non-empty.
    designationOps: [],
    // Stage 1a commit 1a.6 — voice-latency `field_corrected` event
    // accumulator. Pushed to by dispatchClearReading (clear_reading
    // reason) and by same-turn correction in
    // applyReadingToSnapshot/perTurnWrites bookkeeping (overwrite of a
