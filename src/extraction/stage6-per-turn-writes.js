/**
 * Stage 6 Phase 2 Plan 02-02 — Per-turn writes accumulator.
 *
 * WHAT: `createPerTurnWrites()` returns a fresh accumulator that the six write
 * dispatchers (Plans 02-03 + 02-04) push into as they mutate session state.
 * The Phase 2 event bundler (Plan 02-05) reads this accumulator AFTER the
 * tool-loop completes and translates its contents into the legacy `extraction`
 * result shape so iOS receives byte-identical traffic.
 *
 * WHY this is a factory (NOT a singleton on session): Research §Pattern 3 +
 * Pitfall 2. The accumulator resets per user turn. A singleton risks state
 * leaking from turn N into turn N+1's dedup/correction logic. The factory
 * contract forces the shadow harness (Plan 02-06) to new-up a fresh instance
 * every time it invokes `runToolLoop`.
 *
 * ---------------------------------------------------------------------------
 * SHAPE LOCK (MAJOR-1 — DO NOT MUTATE WITHOUT UPDATING PLAN 02-02)
 * ---------------------------------------------------------------------------
 * `readings` is a Map keyed by `${field}::${circuit}`. Its VALUES carry
 * {value, confidence, source_turn_id, auto_resolved?, boardId?} — and NOTHING
 * ELSE (enumerable). Specifically, `field` and `circuit` MUST NOT appear as
 * ENUMERABLE keys on the value object; they live in the Map key and are
 * reconstructed by splitting on '::' in Plan 02-05's bundler.
 *
 * P5 (2026-07-23, same-turn clear→write wipe): value objects — and each
 * `cleared` / `fieldCorrections` entry — additionally carry a NON-ENUMERABLE
 * `[EFFECTIVE_CIRCUIT_SLOT]` slot-identity object `{field, circuit, boardId}`,
 * where `boardId` is the EFFECTIVE board resolved at dispatch time
 * (`input.board_id ?? currentBoardId ?? main`, producer-specific). It exists
 * so the bundler's clear→write collapse can match a clear against its
 * surviving replacement write under EFFECTIVE (not raw-spelling) board
 * identity. Non-enumerable → the enumerable shape, JSON.stringify output and
 * the wire bytes stay byte-identical; the shape tests assert the Symbol is
 * present but non-enumerable.
 *
 * `boardId` was added in the "Work on Board" hotfix slice 1.1a (2026-05-08)
 * so the bundler can emit `reading.board_id` on the wire and the iOS apply
 * path can route by (boardId, circuitRef) rather than pinning to boards[0].
 * The Map key shape stays at `${field}::${circuit}` for slice 1.1a; slice
 * 1.1c extends the key to include boardId so cross-board same-turn writes
 * (`set_field_for_all_circuits('*')`) don't collide.
 *
 * Why: duplicating field/circuit in both the key and the value creates a
 * truth-divergence risk (which one does the bundler trust if they disagree?)
 * and silently breaks same-turn correction (the key is the correction
 * identity; if the value also carries an older copy, refactors drift).
 *
 * If a new Phase ever NEEDS more metadata in the value object, add it
 * alongside value/confidence/source_turn_id/boardId — but do NOT re-introduce
 * field/circuit. The tests in `stage6-per-turn-writes.test.js` assert this
 * shape and will fail if anyone re-adds those keys.
 * ---------------------------------------------------------------------------
 *
 * Slot semantics:
 *   readings            : Map<"${field}::${circuit}",
 *                              {value, confidence, source_turn_id, boardId?, auto_resolved?}>
 *                         Last-write-wins (same-turn correction path).
 *   boardReadings       : Map<field,
 *                              {value, confidence, source_turn_id, boardId?, auto_resolved?}>
 *                         Phase 2 carryover (Bug C — 2026-04-26 production analysis):
 *                         supply / installation / board-level writes via
 *                         record_board_reading. Keyed by field ONLY (no circuit —
 *                         these always live at circuits[0] in the snapshot, so
 *                         the circuit half of the key is constant and degenerate).
 *                         Last-write-wins on field, mirroring readings'
 *                         same-turn correction path. Empty Map => bundler
 *                         OMITS the `extracted_board_readings` slot.
 *   cleared             : Array<{field, circuit, reason}>
 *                         Append-only. Order-preserving for bundler stability.
 *   observations        : Array<{id, code, location, text, circuit, suggested_regulation}>
 *                         Append-only. `id` generated by dispatcher in Plan 02-04.
 *   deletedObservations : Array<{id, reason}>
 *                         Append-only.
 *   circuitOps          : Array<{op: 'create'|'rename'|'update', circuit_ref, from_ref?, meta}>
 *                         Append-only. Phase 2 supports create/rename/update;
 *                         Phase 3+ may extend `op`.
 *   boardOps            : Array<{op: 'add_board'|'select_board'|'mark_distribution_circuit', ...payload}>
 *                         Phase 6.0 — multi-board sprint Codex deal-breaker #3.
 *                         Append-only wire channel for board mutations dispatched
 *                         by Phase 6 tools (`add_board`, `select_board`,
 *                         `mark_distribution_circuit`). Discriminated by `op`;
 *                         each op carries the payload Sonnet emitted (board id,
 *                         designation, board_type, circuit_ref, etc.). Inert
 *                         until Phase 6 dispatchers write — bundler emits the
 *                         `board_ops` slot only when non-empty so pre-Phase-6
 *                         traffic stays byte-identical to today.
 */

/**
 * P5 (2026-07-23) — non-enumerable slot-identity marker. Attached at DISPATCH
 * time to each `readings` VALUE object and each `cleared` / `fieldCorrections`
 * entry, carrying `{field, circuit, boardId}` where `boardId` is the EFFECTIVE
 * board (raw spelling resolved to the real board once). The bundler's
 * clear→write collapse and `dispatchClearReading`'s same-turn delete both key
 * off this so an omitted vs explicit-current `board_id` spelling denotes the
 * SAME slot. Non-enumerable: the enumerable value shape and wire bytes are
 * unchanged.
 */
export const EFFECTIVE_CIRCUIT_SLOT = Symbol('stage6.effectiveCircuitSlot');

/**
 * P5 — the ONE shared slot-DERIVATION helper used by BOTH `dispatchClearReading`'s
 * effective-aware delete and the bundler's clear→write collapse projection.
 * Builds a stable identity STRING from raw `(field, circuit, boardId)` parts.
 *
 * It is a pure derivation only — it does NOT decide WHEN the raw fallback
 * applies; that gating is per call site (the delete gates on the entry side;
 * the projection requires BOTH compared sides to be Symbol-less). Fed the
 * EFFECTIVE board it yields the effective key; fed a RAW board it yields the
 * fallback key. `boardId` of null / '' / undefined collapses to the same
 * empty segment (mirroring `decodeReadingKey`'s null normalisation and the
 * dispatcher's `board_id ?? null`), so a null-board clear matches a null-board
 * write. NUL joins never collide with field (snake_case), circuit (digits /
 * short ref), or board id (`::`/NUL forbidden by `encodeReadingKey`).
 *
 * @param {string} field
 * @param {number|string} circuit
 * @param {string|null|undefined} boardId
 * @returns {string}
 */
export function rawCircuitSlot(field, circuit, boardId) {
  const normBoard = boardId == null || boardId === '' ? '' : String(boardId);
  return `${String(field)}\u0000${String(circuit)}\u0000${normBoard}`;
}

/**
 * P5 — attach the non-enumerable EFFECTIVE_CIRCUIT_SLOT marker to a
 * perTurnWrites value / cleared / fieldCorrections entry. `effectiveBoardId`
 * is the resolved board (never a raw spelling, never the '*' broadcast
 * selector; null-normalised). Non-enumerable so the enumerable shape, JSON
 * output and wire bytes stay byte-identical. Returns `target` for chaining.
 */
export function attachEffectiveSlot(target, field, circuit, effectiveBoardId) {
  Object.defineProperty(target, EFFECTIVE_CIRCUIT_SLOT, {
    value: { field, circuit, boardId: effectiveBoardId ?? null },
    enumerable: false,
    configurable: true,
    writable: false,
  });
  return target;
}

/**
 * Plan A1a (2026-07-27) — non-enumerable BOARD slot-identity marker, the
 * board twin of EFFECTIVE_CIRCUIT_SLOT. Attached at DISPATCH time to each
 * `boardReadings` VALUE object (dispatchRecordBoardReading) and each board
 * `fieldCorrections` entry (dispatchClearBoardReading). Carries
 * `{field, boardId}` where `field` is the CANONICAL member of the field's
 * alias set (never the raw spelling the model used) and `boardId` is —
 * SCOPE-CONDITIONALLY — the resolved board id for BOARD-SCOPED fields and
 * `null` for GLOBAL fields (a global field's slot is board-INSENSITIVE:
 * select_board is a no-op on it, so a write on board A and a clear on board
 * B are one and the same slot). Non-enumerable so it never rides the wire
 * or a spread.
 *
 * WHY this exists: the live `perTurnWrites.boardReadings` map key is
 * BOARDLESS for schema-conforming model calls (record_board_reading has no
 * board_id param, so encodeBoardReadingKey gets `undefined`), which means
 * the raw key does NOT identify the board a write actually hit. Matching
 * clear-vs-write on raw keys either collapses cross-board operations on a
 * board-scoped field (silently unspeaking a real dictated reading — Audio
 * First #1) or misses same-slot alias-spelling pairs entirely.
 */
export const EFFECTIVE_BOARD_SLOT = Symbol('stage6.effectiveBoardSlot');

/**
 * Plan A1a — stable identity STRING for a board slot, shared by the
 * dispatcher's same-turn write delete (mechanism A), the bundler's board
 * clear→write collapse (mechanism B), the #31 spoken-clear suppression, and
 * the mandatory-notice same-slot dedupe. ONE derivation for all four — two
 * derivations is how they drift.
 *
 * `boardId` MUST already be the scope-conditioned value (resolved id for
 * board-scoped fields, null for global fields); this helper does not know
 * scopes.
 */
export function boardSlotKey(canonicalField, boardId) {
  const normBoard = boardId == null || boardId === '' ? '' : String(boardId);
  return `${String(canonicalField)}\u0000__boardslot__\u0000${normBoard}`;
}

/**
 * Plan A1a — attach the non-enumerable EFFECTIVE_BOARD_SLOT marker.
 * `canonicalField` is the canonical alias-set member; `effectiveBoardId` is
 * the resolved board for board-scoped fields and null for global fields.
 * Returns `target` for chaining.
 */
export function attachEffectiveBoardSlot(target, canonicalField, effectiveBoardId) {
  Object.defineProperty(target, EFFECTIVE_BOARD_SLOT, {
    value: { field: canonicalField, boardId: effectiveBoardId ?? null },
    enumerable: false,
    configurable: true,
    writable: false,
  });
  return target;
}

