    //   { circuit: <int>, field: <string>, previous_value: <string|null>,
    //     reason: 'clear_reading' | 'same_turn_correction' | 'replace_value' }
    // Plus an optional `board_id` for multi-board sessions.
    // The bundler/orchestrator emits each entry as a separate
    // `field_corrected` WS event after the extraction envelope lands;
    // iOS Stage6Messages.swift:138-165 already decodes this shape.
    fieldCorrections: [],
    // F/U-2/3 (2026-07-19) — dispatcher voice NOTICES: short deterministic
    // spoken lines a dispatcher wants the inspector to hear about a
