// ---------------------------------------------------------------------------
// "Work on Board" hotfix slice 1.1c (2026-05-08) — collision-safe Map keys
// ---------------------------------------------------------------------------
//
// Phase A's bare `${field}::${circuit}` key collided whenever a single
// tool-loop turn wrote the same (field, circuit) pair on two boards — e.g.
// `set_field_for_all_circuits('*')` over a 2-board job, or any future tool
// that writes per-circuit across boards in one round. The second write
// silently overwrote the first because Map.set is last-write-wins and the
// key shape couldn't tell them apart.
//
// Encoding contract (must be implemented exactly as written — see PLAN.md
// slice 1.1c, Codex caught underspecification in v2 review):
//
//   readings        : `${field}::${circuit}` + BOARD_TAG_SEP + `${boardId??''}` + BOARD_TAG_END
//   boardReadings   : `${field}`              + BOARD_TAG_SEP + `${boardId??''}` + BOARD_TAG_END
//
// where:
//   BOARD_TAG_SEP = '\u0000__board__\u0000'  (NUL-bracketed sentinel)
//   BOARD_TAG_END = '\u0000'                  (trailing NUL)
//
// Why NUL-bracketed (rather than bare `__main__`): NUL bytes never appear
// in field names (snake_case identifiers), circuit refs (digits or short
// strings), or any plausible board id (UUIDs / `main` / `sub-N` /
// designation-derived ids). Eliminates the "real boardId == '__main__'"
// collision concern Codex flagged in v2.
//
// Empty-string normalisation: `boardId === ''` is treated as
// `boardId === null/undefined`. The dispatcher / mutator layer already
// coerces empty boardId to "main board default" via resolveBoardId; the
// encoder mirrors that contract so the Map key never carries an empty
// boardId tag suffix.
//
// `::` in boardId is forbidden at write time (TypeError) — board ids today
// are UUIDs / `main` / `sub-N`, none contain `::`. Defensive against future
// board-id schemes that might include it (e.g. designation-derived ids
// like `kitchen::sub` would silently break the decoder's last-`::` split).
//
// Legacy 2-part key compat: if a key contains NO BOARD_TAG_SEP (pre-hotfix
// test fixture or older accumulator), decode with the OLD 2-part rule
// `field::circuit` and emit boardId === null. Bundler then omits the
// `board_id` wire field, matching slice 1.1a's omit-when-undefined contract.

const BOARD_TAG_SEP = '\u0000__board__\u0000';
const BOARD_TAG_END = '\u0000';

/**
 * Build a `readings` Map key. boardId of '' / null / undefined collapses to
 * an empty boardId segment that the decoder reports back as `null`.
 *
 * @throws {TypeError} if boardId contains BOARD_TAG_SEP, BOARD_TAG_END, or `::`.
 */
export function encodeReadingKey(field, circuit, boardId) {
  const normalised = boardId == null || boardId === '' ? '' : String(boardId);
  if (normalised !== '') {
    if (normalised.includes('::')) {
      throw new TypeError(
        `encodeReadingKey: boardId must not contain '::' (got ${JSON.stringify(normalised)})`
      );
    }
    if (normalised.includes(BOARD_TAG_END)) {
      throw new TypeError(
        `encodeReadingKey: boardId must not contain NUL (got ${JSON.stringify(normalised)})`
      );
    }
  }
  return `${field}::${circuit}${BOARD_TAG_SEP}${normalised}${BOARD_TAG_END}`;
}

/**
 * Decode a `readings` Map key into {field, circuit, boardId}. Tolerates
 * legacy 2-part keys (no BOARD_TAG_SEP) — those decode to `boardId === null`,
 * mirroring the pre-hotfix contract.
 *
 * - boardId === '' (empty between the two NULs) decodes to `null`.
 * - field+circuit segment splits on the LAST '::' (field names never carry
 *   '::'; using last is defensive against any future schema oddity).
 *
 * @returns {{field: string, circuit: string, boardId: string|null}}
 */
export function decodeReadingKey(key) {
  const sepIdx = key.indexOf(BOARD_TAG_SEP);
  let leftSegment;
  let boardId = null;
  if (sepIdx < 0) {
    // Legacy 2-part key — pre-hotfix test fixture or older accumulator.
    leftSegment = key;
  } else {
    leftSegment = key.slice(0, sepIdx);
    let rightSegment = key.slice(sepIdx + BOARD_TAG_SEP.length);
    if (rightSegment.endsWith(BOARD_TAG_END)) {
      rightSegment = rightSegment.slice(0, -BOARD_TAG_END.length);
    }
    boardId = rightSegment === '' ? null : rightSegment;
  }
  const lastSep = leftSegment.lastIndexOf('::');
  if (lastSep < 0) {
    return { field: leftSegment, circuit: '', boardId };
  }
  return {
    field: leftSegment.slice(0, lastSep),
    circuit: leftSegment.slice(lastSep + 2),
    boardId,
  };
}

/**
 * Build a `boardReadings` Map key. Same contract as encodeReadingKey except
 * the left segment is just `${field}` (no `::circuit` — degenerate slot).
 */
export function encodeBoardReadingKey(field, boardId) {
  const normalised = boardId == null || boardId === '' ? '' : String(boardId);
  if (normalised !== '') {
    if (normalised.includes('::')) {
      throw new TypeError(
        `encodeBoardReadingKey: boardId must not contain '::' (got ${JSON.stringify(normalised)})`
      );
    }
    if (normalised.includes(BOARD_TAG_END)) {
      throw new TypeError(
        `encodeBoardReadingKey: boardId must not contain NUL (got ${JSON.stringify(normalised)})`
      );
    }
  }
  return `${field}${BOARD_TAG_SEP}${normalised}${BOARD_TAG_END}`;
}

/**
 * Decode a `boardReadings` Map key into {field, boardId}. Tolerates legacy
 * field-only keys.
 *
 * @returns {{field: string, boardId: string|null}}
 */
export function decodeBoardReadingKey(key) {
  const sepIdx = key.indexOf(BOARD_TAG_SEP);
  if (sepIdx < 0) {
    return { field: key, boardId: null };
  }
  let rightSegment = key.slice(sepIdx + BOARD_TAG_SEP.length);
  if (rightSegment.endsWith(BOARD_TAG_END)) {
    rightSegment = rightSegment.slice(0, -BOARD_TAG_END.length);
  }
  return {
    field: key.slice(0, sepIdx),
    boardId: rightSegment === '' ? null : rightSegment,
  };
}
